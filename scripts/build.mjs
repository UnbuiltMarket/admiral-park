import {readFile,writeFile} from "node:fs/promises";
import {stripTypeScriptTypes} from "node:module";
const root = new URL("../", import.meta.url);
const core = await readFile(new URL("src/core/hero-player.ts",root),"utf8");
const wrapper = await readFile(new URL("src/framer/AdmiralHeroVideo.source.tsx",root),"utf8");
const compiled = stripTypeScriptTypes(core,{mode:"strip"}).replace(/[ \t]+$/gm,"");
await writeFile(new URL("src/core/hero-player.js",root),"// Generated by scripts/build.mjs. Edit hero-player.ts.\n"+compiled);
const single = "// Generated single-file Framer component. Paste this entire file into Framer.\n" + wrapper.replace("// @CORE_INSERT",core);
stripTypeScriptTypes(single,{mode:"strip"});
await writeFile(new URL("src/framer/AdmiralHeroVideo.tsx",root),single);
console.log("Built browser player and single-file Framer component.");
