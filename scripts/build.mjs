import {readFile,writeFile} from "node:fs/promises";
import {compileTS,inlineCore} from "./tooling.mjs";
const root=new URL("../",import.meta.url);
const core=await readFile(new URL("src/core/hero-player.ts",root),"utf8");
const wrapper=await readFile(new URL("src/framer/AdmiralHeroVideo.source.tsx",root),"utf8");
const single="// Generated standalone Framer Code Component. Paste this entire file into Framer.\n"+
  wrapper.replace("// @CORE_INSERT",inlineCore(core)).trimEnd()+"\n";
compileTS(single,"AdmiralHeroVideo.tsx");
await writeFile(new URL("src/core/hero-player.js",root),"// Generated by scripts/build.mjs. Edit hero-player.ts.\n"+compileTS(core,"hero-player.ts"));
await writeFile(new URL("src/framer/AdmiralHeroVideo.tsx",root),single);
console.log("Built browser player and standalone JSX Framer component.");
