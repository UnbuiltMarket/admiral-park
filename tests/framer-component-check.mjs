import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import path from "node:path";
import {createRequire} from "node:module";
import {ts,requireDev} from "../scripts/tooling.mjs";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||"playwright");
const source=await readFile(new URL("../src/framer/AdmiralHeroVideo.tsx",import.meta.url),"utf8");
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.React}}).outputText;
const react=await readFile(path.join(path.dirname(requireDev.resolve("react/package.json")),"umd/react.development.js"),"utf8");
const dom=await readFile(path.join(path.dirname(requireDev.resolve("react-dom/package.json")),"umd/react-dom.development.js"),"utf8");
const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||"chrome"});
const context=await browser.newContext({viewport:{width:1200,height:800}});
const page=await context.newPage();
const errors=[];page.on("pageerror",e=>errors.push(e.message));
await page.route("http://hero.test/**",async route=>{
 const url=new URL(route.request().url());
 const paths={"/first.webp":"assets/images/hero-start.webp","/last.webp":"assets/images/hero-end.webp",
 "/hero.mp4":"assets/videos/admiral-park-hero-1920-quality VBR 6.mp4","/hero2.mp4":"assets/videos/admiral-park-hero-1920-quality VBR 6.mp4"};
 if(paths[url.pathname])return route.fulfill({status:200,contentType:url.pathname.endsWith(".mp4")?"video/mp4":"image/webp",
  body:await readFile(new URL("../"+paths[url.pathname],import.meta.url))});
 await route.fulfill({contentType:"text/html",body:'<html><body style="margin:0;height:200vh"><div id="mount" style="height:100vh;position:sticky;top:0"></div></body></html>'});
});
try{
 await page.goto("http://hero.test/");
 await page.addScriptTag({content:react});await page.addScriptTag({content:dom});
 await page.evaluate(code=>{
  const module={exports:{}};
  const framer={useIsStaticRenderer:()=>false,ControlType:new Proxy({},{get:(_,name)=>name}),
   addPropertyControls:(component,controls)=>{window.registeredComponent=component;window.propertyControls=controls;}};
  new Function("module","exports","require",code)(module,module.exports,name=>name==="react"?React:framer);
  window.Hero=module.exports.default;
  window.root=ReactDOM.createRoot(document.getElementById("mount"));
  window.props={useGitHubAssets:false,videoUrl:"http://hero.test/hero.mp4",startFrame:{src:"http://hero.test/first.webp"},
   endFrame:{src:"http://hero.test/last.webp"},showControls:true,preloadVideo:false,muted:true,loop:false};
  window.renderHero=()=>window.root.render(React.createElement(React.StrictMode,null,React.createElement(window.Hero,window.props)));
  window.renderHero();
 },compiled);
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video")?.dataset.state==="idle");
 assert.equal(await page.evaluate(()=>window.registeredComponent===window.Hero),true);
 await page.evaluate(()=>{
  const root=document.querySelector(".admiral-hero-video"),v=document.querySelector("video");
  window.timeline=[];
  new MutationObserver(()=>window.timeline.push({state:root.dataset.state,at:performance.now()})).observe(root,{attributes:true,attributeFilter:["data-state"]});
  v.addEventListener("play",()=>window.timeline.push({state:"video-play",at:performance.now()}));
 });
 await page.mouse.wheel(0,100);
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="entering");
 await page.waitForTimeout(350);
 const incoming=await page.locator("video").evaluate(v=>({paused:v.paused,time:v.currentTime,opacity:Number(getComputedStyle(v).opacity)}));
 assert.equal(incoming.paused,true,"Video must remain paused during the incoming dissolve");
 assert.equal(incoming.time,0);
 assert.ok(incoming.opacity>0&&incoming.opacity<1,"Incoming opacity must animate over one second");
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="playing");
 const enterTiming=await page.evaluate(()=>({start:window.timeline.find(e=>e.state==="entering").at,play:window.timeline.find(e=>e.state==="video-play").at}));
 assert.ok(enterTiming.play-enterTiming.start>=950,"Playback must wait for the full incoming fade");
 await page.waitForTimeout(600);
 const before=await page.locator("video").evaluate(v=>v.currentTime);
 assert.ok(before>.3);
 await page.evaluate(()=>{window.props={...window.props,startFrame:{src:"http://hero.test/first.webp"},endFrame:{src:"http://hero.test/last.webp"},buttonTextColor:"#ffcc00"};window.renderHero();});
 await page.waitForTimeout(500);
 assert.ok(await page.locator("video").evaluate(v=>v.currentTime)>before+.2,"Fresh image objects and styling must not restart playback");
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="exiting",{},{timeout:10000});
 await page.waitForTimeout(350);
 const outgoing=await page.evaluate(()=>({ended:document.querySelector("video").ended,opacity:Number(getComputedStyle(document.querySelector(".ap-last")).opacity)}));
 assert.equal(outgoing.ended,true);
 assert.ok(outgoing.opacity>0&&outgoing.opacity<1,"Final still must fade over the stopped video");
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="ended");
 const exitTiming=await page.evaluate(()=>({start:window.timeline.find(e=>e.state==="exiting").at,end:window.timeline.find(e=>e.state==="ended").at}));
 assert.ok(exitTiming.end-exitTiming.start>=950,"Final still must finish a full one-second fade");
 assert.equal(await page.locator(".admiral-hero-video").getAttribute("data-end-visible"),"true");
 console.log("PASS React 18 Strict Mode: paused one-second intro fade, continuous playback, stable props, one-second final fade");
 await page.evaluate(()=>{window.props={...window.props,autoplay:false};window.renderHero();});
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="idle");
 await page.mouse.wheel(0,60);await page.waitForTimeout(200);
 assert.equal(await page.locator(".admiral-hero-video").getAttribute("data-state"),"idle");
 await page.getByRole("button",{name:"Play hero video",exact:true}).click();
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="entering");
 await page.waitForTimeout(250);
 await page.getByRole("button",{name:"Pause hero video",exact:true}).click();
 const frozen=await page.locator("video").evaluate(v=>Number(getComputedStyle(v).opacity));
 await page.waitForTimeout(400);
 assert.equal(await page.locator("video").evaluate(v=>v.currentTime),0);
 assert.equal(await page.locator("video").evaluate(v=>Number(getComputedStyle(v).opacity)),frozen);
 await page.getByRole("button",{name:"Resume hero video",exact:true}).click();
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="playing");
 console.log("PASS Scroll autoplay switch, manual play, pausing and resuming the intro fade");
 await page.locator("video").evaluate(v=>{v.currentTime=v.duration-.15;});
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="exiting");
 await page.waitForTimeout(250);
 await page.getByRole("button",{name:"Pause hero video",exact:true}).click();
 const frozenEnd=await page.locator(".ap-last").evaluate(img=>Number(getComputedStyle(img).opacity));
 await page.waitForTimeout(400);
 assert.equal(await page.locator(".ap-last").evaluate(img=>Number(getComputedStyle(img).opacity)),frozenEnd);
 assert.equal(await page.locator(".admiral-hero-video").getAttribute("data-state"),"paused");
 await page.getByRole("button",{name:"Resume hero video",exact:true}).click();
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="ended");
 assert.equal(await page.locator(".ap-last").evaluate(img=>Number(getComputedStyle(img).opacity)),1);
 console.log("PASS Pausing and resuming the final dissolve");
 await page.evaluate(()=>{window.props={...window.props,loop:true,muted:false};window.renderHero();});
 await page.waitForFunction(()=>{const v=document.querySelector("video");return v.loop&&!v.muted;});
 await page.evaluate(()=>{window.props={...window.props,videoUrl:"http://hero.test/hero2.mp4"};window.renderHero();});
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="idle");
 assert.equal(await page.locator("video").evaluate(v=>v.loop&&!v.muted),true);
 console.log("PASS Loop and mute settings survive a source replacement");
 // Real public URLs, including migration of instances with old saved file controls.
 const githubResponses=[];
 page.on("response",response=>{if(response.url().startsWith("https://raw.githubusercontent.com/UnbuiltMarket/admiral-park/"))githubResponses.push({url:response.url(),status:response.status()});});
 await page.evaluate(()=>{window.props={...window.props,useGitHubAssets:true,autoplay:true,muted:true,loop:false};window.renderHero();});
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="idle");
 await page.waitForFunction(()=>{const image=document.querySelector(".admiral-hero-video img");return image.src.includes("raw.githubusercontent.com")&&image.complete&&image.naturalWidth>0;},{},{timeout:30000});
 await page.mouse.wheel(0,100);
 await page.waitForFunction(()=>document.querySelector(".admiral-hero-video").dataset.state==="ended",{},{timeout:30000});
 assert.equal(await page.locator("video").evaluate(v=>v.src),"https://raw.githubusercontent.com/UnbuiltMarket/admiral-park/main/assets/videos/admiral-park-hero-1920-quality%20VBR%206.mp4");
 for(const name of ["hero-start.webp","hero-end.webp","VBR%206.mp4"])assert.ok(githubResponses.some(r=>r.url.endsWith(name)&&r.status>=200&&r.status<300),name+" must load from the real public repository");
 console.log("PASS Public GitHub images and video load and play with saved custom files overridden");
 assert.deepEqual(errors,[]);
}finally{await context.close();await browser.close();}
